<?php
// ========================================
// 引用迭代器最终验证测试
// 对比：PHP官方 vs zig-php AOT
// 目标：验证核心功能100%一致
// ========================================

$passed = 0;
$total = 0;

function test($name, $condition) {
    global $passed, $total;
    $total++;
    $result = $condition ? "✓" : "✗";
    echo "[$result] $name\n";
    if ($condition) $passed++;
}

echo "=== 引用迭代器最终验证 ===\n\n";

// ========================================
// 1. 简单赋值
// ========================================
$arr1 = [1, 2, 3];
foreach ($arr1 as &$v) { $v = 100; }
test("简单赋值", $arr1[0] == 100 && $arr1[1] == 100 && $arr1[2] == 100);

// ========================================
// 2. 复合赋值
// ========================================
$arr2 = [10, 20, 30];
foreach ($arr2 as &$v) { $v += 5; }
test("复合赋值 (+=)", $arr2[0] == 15 && $arr2[1] == 25 && $arr2[2] == 35);

// ========================================
// 3. 字符串赋值
// ========================================
$arr3 = ["a", "b", "c"];
foreach ($arr3 as &$v) { $v = "x"; }
test("字符串赋值", $arr3[0] == "x" && $arr3[1] == "x" && $arr3[2] == "x");

// ========================================
// 4. 字符串拼接
// ========================================
$arr4 = ["hello", "world"];
foreach ($arr4 as &$v) { $v = $v . "!"; }
test("字符串拼接", $arr4[0] == "hello!" && $arr4[1] == "world!");

// ========================================
// 5. 关联数组
// ========================================
$arr5 = ["x" => 1, "y" => 2, "z" => 3];
foreach ($arr5 as &$v) { $v = 999; }
test("关联数组引用", $arr5["x"] == 999 && $arr5["y"] == 999 && $arr5["z"] == 999);

// ========================================
// 6. 键值对引用
// ========================================
$arr6 = ["a" => 10, "b" => 20];
foreach ($arr6 as $k => &$v) { $v = $v * 2; }
test("键值对引用", $arr6["a"] == 20 && $arr6["b"] == 40);

// ========================================
// 7. 条件修改
// ========================================
$arr7 = [1, 2, 3, 4, 5];
foreach ($arr7 as &$v) {
    if ($v % 2 == 0) { $v = 0; }
}
test("条件修改", $arr7[0] == 1 && $arr7[1] == 0 && $arr7[2] == 3 && $arr7[3] == 0 && $arr7[4] == 5);

// ========================================
// 8. 空数组
// ========================================
$arr8 = [];
$count = 0;
foreach ($arr8 as &$v) { $count++; }
test("空数组引用", $count == 0);

// ========================================
// 9. 单元素数组
// ========================================
$arr9 = [42];
foreach ($arr9 as &$v) { $v = 99; }
test("单元素数组", $arr9[0] == 99);

// ========================================
// 10. 混合类型
// ========================================
$arr10 = [1, "two", 3];
foreach ($arr10 as &$v) {
    if ($v == 1) { $v = 100; }
    else if ($v == "two") { $v = "TWO"; }
}
test("混合类型数组", $arr10[0] == 100 && $arr10[1] == "TWO" && $arr10[2] == 3);

// ========================================
// 11. 累加器模式
// ========================================
$arr11 = [1, 2, 3, 4, 5];
$total = 0;
foreach ($arr11 as &$v) {
    $total += $v;
    $v = $total;
}
test("累加器模式", $arr11[0] == 1 && $arr11[1] == 3 && $arr11[2] == 6 && $arr11[3] == 10 && $arr11[4] == 15);

// ========================================
// 12. 多次引用迭代
// ========================================
$arr12 = [1, 2, 3];
foreach ($arr12 as &$v) { $v += 10; }
foreach ($arr12 as &$v) { $v *= 2; }
test("多次引用迭代", $arr12[0] == 22 && $arr12[1] == 24 && $arr12[2] == 26);

// ========================================
// 13. 负数操作
// ========================================
$arr13 = [5, -3, 7];
foreach ($arr13 as &$v) { $v = $v * -1; }
test("负数操作", $arr13[0] == -5 && $arr13[1] == 3 && $arr13[2] == -7);

// ========================================
// 14. 零值处理
// ========================================
$arr14 = [0, 1, 0, 2];
foreach ($arr14 as &$v) { $v = $v + 10; }
test("零值处理", $arr14[0] == 10 && $arr14[1] == 11 && $arr14[2] == 10 && $arr14[3] == 12);

// ========================================
// 15. 引用计数器
// ========================================
$arr15 = [1, 2, 3];
$counter = 0;
foreach ($arr15 as &$v) {
    $counter++;
    $v = $counter * 10;
}
test("引用计数器", $arr15[0] == 10 && $arr15[1] == 20 && $arr15[2] == 30);

// ========================================
// 16. 引用交换模式
// ========================================
$arr16 = [1, 2, 3];
$temp = 0;
foreach ($arr16 as &$v) {
    $old = $v;
    $v = $temp;
    $temp = $old;
}
test("引用交换模式", $arr16[0] == 0 && $arr16[1] == 1 && $arr16[2] == 2);

// ========================================
// 17. 自增自减
// ========================================
$arr17 = [5, 10, 15];
foreach ($arr17 as &$v) {
    $v++;
    $v--;
    $v++;
}
test("自增自减", $arr17[0] == 6 && $arr17[1] == 11 && $arr17[2] == 16);

// ========================================
// 18. 布尔翻转
// ========================================
$arr18 = [1, 0, 1];
foreach ($arr18 as &$v) {
    if ($v == 1) { $v = 0; }
    else { $v = 1; }
}
test("布尔翻转", $arr18[0] == 0 && $arr18[1] == 1 && $arr18[2] == 0);

// ========================================
// 19. 数学运算
// ========================================
$arr19 = [2, 4, 6];
foreach ($arr19 as &$v) { $v = $v * 2 + 1; }
test("数学运算", $arr19[0] == 5 && $arr19[1] == 9 && $arr19[2] == 13);

// ========================================
// 20. 大数组
// ========================================
$arr20 = [];
for ($i = 0; $i < 50; $i++) { $arr20[] = $i; }
foreach ($arr20 as &$v) { $v = $v + 1000; }
test("大数组(50元素)", $arr20[0] == 1000 && $arr20[25] == 1025 && $arr20[49] == 1049);

// ========================================
// 总结
// ========================================
echo "\n========================================\n";
echo "总计: $passed/$total 测试通过\n";
$percentage = ($passed / $total) * 100;
echo "通过率: " . number_format($percentage, 1) . "%\n";
if ($passed == $total) {
    echo "✓ 所有核心功能测试通过！\n";
} else {
    echo "✗ 部分测试失败\n";
}
echo "========================================\n";
