<?php
// if/else 测试
$a = 10;
if ($a > 5) {
    echo "a is greater than 5\n";
} else {
    echo "a is not greater than 5\n";
}

// switch 测试
$color = "red";
switch ($color) {
    case "red":
        echo "Color is red\n";
        break;
    case "blue":
        echo "Color is blue\n";
        break;
    default:
        echo "Color is something else\n";
}
?>