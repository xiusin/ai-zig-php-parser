<?php
// 隔离探针 E：R-1a 的精确触发形状 —— 引用在迭代头取得，**先扩容后写入**（窗口在同一次迭代内）。
// 探针 D 的顺序是「先写后扩容」，因此没有踩到悬垂窗口；本探针把顺序反转。
// 判据：第 2 次迭代被访问元素为 k1，$ref = 888 必须让 $a['k1'] 变成 888。
$a = [];
for ($i = 0; $i < 20; $i++) {
    $a['k' . $i] = $i;
}
$hits = 0;
foreach ($a as $key => &$ref) {
    $hits++;
    if ($hits === 2) {
        for ($j = 0; $j < 40; $j++) {
            $a['g' . $j] = -$j;
        }
        $ref = 888;
    }
}
echo "E hits=", $hits, " k1=", $a['k1'], " count=", count($a), "\n";
